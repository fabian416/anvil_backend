async def test_user_shortcut_examples_have_meaningful_content(
    client: AsyncClient,
    shortcuts_data: list,
    conversation_id: str,
):
    """
    Test that all shortcut examples return responses with meaningful content.
    
    CTO Framework: Quality Assurance Phase
    - Dynamically fetches shortcuts from API endpoint
    - Tests each example from each shortcut
    - Verifies responses contain relevant information
    - Ensures minimum content length
    - Checks for intent-specific keywords
    - Outputs detailed results for each example
    """
    failures = []
    successes = []
    
    # Intent-specific keywords that should appear in responses
    intent_keywords = {
        "lending": ["lending", "vault", "yield", "morpho", "deposit"],
        "money_market": ["aave", "compound", "rate", "supply", "lending"],
        "swap": ["swap", "quote", "rate", "bridge", "exchange"],
        "portfolio": ["portfolio", "dashboard", "holdings", "assets", "tokens"],
        "balance": ["balance", "wallet", "account", "required"],
        "activity": ["transaction", "history", "activity", "account", "required"],
        "receive": ["address", "wallet", "receive", "deposit", "required"],
        "buy": ["buy", "crypto", "card", "account", "required"],
        "send": ["send", "transfer", "wallet", "account", "required"],
    }
    
    print(f"\n{'='*80}")
    print("CTO Framework: Content Quality Assurance")
    print(f"{'='*80}")
    print(f"Total shortcuts: {len(shortcuts_data)}")
    print(f"{'='*80}\n")
    
    for shortcut in shortcuts_data:
        intent = shortcut["intent"]
        command = shortcut["command"]
        examples = shortcut.get("examples", [])
        
        print(f"\n📋 Testing Shortcut: {command} (intent: {intent})")
        
        for idx, example in enumerate(examples, 1):
            print(f"   [{idx}/{len(examples)}] Testing: '{example}'")
            
            response = await client.post(
                f"/api/v1/user/chat/conversations/{conversation_id}/messages",
                json={"content": example, "language": "en"},
                headers={"Authorization": f"Bearer {ACCESS_TOKEN}"},
            )
            
            # Accept both 200 (existing conversation) and 201 (new conversation created)
            assert response.status_code in [200, 201], (
                f"Failed for {intent}: {example} - Status: {response.status_code}"
            )
            data = response.json()
            
            content = data.get("agent_message", {}).get("content", "").lower()
            
            # Check minimum content length
            if len(content) < 50:
                print(f"      ❌ Content too short: {len(content)} chars")
                failures.append({
                    "shortcut": command,
                    "intent": intent,
                    "example": example,
                    "issue": "Content too short",
                    "length": len(content),
                })
                continue
            
            # Check for intent-specific keywords
            if intent in intent_keywords:
                keywords = intent_keywords[intent]
                found_keyword = any(keyword in content for keyword in keywords)
                
                if not found_keyword:
                    print(f"      ❌ No intent keywords found (expected: {keywords})")
                    print(f"      Content: {content[:100]}...")
                    failures.append({
                        "shortcut": command,
                        "intent": intent,
                        "example": example,
                        "issue": "No intent-specific keywords found",
                        "expected_keywords": keywords,
                        "content_preview": content[:150],
                    })
                else:
                    print(f"      ✅ Content quality OK (length: {len(content)}, keywords found)")
                    successes.append({
                        "shortcut": command,
                        "intent": intent,
                        "example": example,
                    })
            else:
                # No specific keywords defined, just check length
                print(f"      ✅ Content quality OK (length: {len(content)})")
                successes.append({
                    "shortcut": command,
                    "intent": intent,
                    "example": example,
                })
    
    print(f"\n{'='*80}")
    print(f"Results: {len(successes)} passed, {len(failures)} failed")
    print(f"{'='*80}\n")
    
    if failures:
        error_msg = "\n".join(
            [
                f"❌ {f['shortcut']} ({f['intent']}): '{f['example']}' → {f['issue']}"
                for f in failures
            ]
        )
        pytest.fail(f"Content quality issues:\n{error_msg}")


@pytest.mark.asyncio
@pytest.mark.integration
async def test_user_shortcut_examples_comprehensive_output(
    client: AsyncClient,
    shortcuts_data: list,
    conversation_id: str,
):
    """
    Comprehensive test that verifies output for each example of each shortcut.
    
    CTO Framework: Comprehensive Verification Phase
    - Dynamically fetches shortcuts from API endpoint
    - Tests each example from each shortcut
    - Verifies complete response structure
    - Outputs detailed information for each example
    - Validates all response fields
    """
    print(f"\n{'='*80}")
    print("CTO Framework: Comprehensive Output Verification")
    print(f"{'='*80}")
    print(f"Total shortcuts: {len(shortcuts_data)}")
    print(f"Conversation ID: {conversation_id}")
    print(f"{'='*80}\n")
    
    all_results = []
    
    for shortcut in shortcuts_data:
        intent = shortcut["intent"]
        command = shortcut["command"]
        description = shortcut.get("description", "")
        examples = shortcut.get("examples", [])
        
        print(f"\n{'='*80}")
        print(f"Shortcut: {command}")
        print(f"Intent: {intent}")
        print(f"Description: {description}")
        print(f"Examples: {len(examples)}")
        print(f"{'='*80}")
        
        shortcut_results = {
            "shortcut": command,
            "intent": intent,
            "description": description,
            "examples": [],
        }
        
        for idx, example in enumerate(examples, 1):
            print(f"\n  Example {idx}/{len(examples)}: '{example}'")
            
            response = await client.post(
                f"/api/v1/user/chat/conversations/{conversation_id}/messages",
                json={"content": example, "language": "en"},
                headers={"Authorization": f"Bearer {ACCESS_TOKEN}"},
            )
            
            # Accept both 200 and 201
            assert response.status_code in [200, 201], (
                f"Failed for {intent}: {example} - Status: {response.status_code}"
            )
            
            data = response.json()
            
            # Extract key information
            detected_intent = data.get("routing", {}).get("intent", "unknown")
            agent_content = data.get("agent_message", {}).get("content", "")
            routing_info = data.get("routing", {})
            enrichment = data.get("enrichment", {})
            
            # Verify response structure
            assert "agent_message" in data, "Response missing 'agent_message'"
            assert "routing" in data, "Response missing 'routing'"
            
            # Build result
            result = {
                "example": example,
                "status_code": response.status_code,
                "detected_intent": detected_intent,
                "content_length": len(agent_content),
                "content_preview": agent_content[:150],
                "routing": routing_info,
                "has_enrichment": bool(enrichment),
                "is_generic_fallback": GENERIC_FALLBACK_MESSAGE in agent_content,
            }
            
            shortcut_results["examples"].append(result)
            
            # Print detailed output
            print(f"    Status: {response.status_code}")
            print(f"    Detected Intent: {detected_intent} {'✅' if detected_intent == intent else '❌'}")
            print(f"    Content Length: {len(agent_content)} chars")
            print(f"    Generic Fallback: {'Yes ❌' if result['is_generic_fallback'] else 'No ✅'}")
            print(f"    Has Enrichment: {'Yes' if result['has_enrichment'] else 'No'}")
            print(f"    Content Preview: {agent_content[:100]}...")
            
            if enrichment:
                print(f"    Enrichment Keys: {list(enrichment.keys())}")
        
        all_results.append(shortcut_results)
    
    # Summary
    print(f"\n{'='*80}")
    print("SUMMARY")
    print(f"{'='*80}")
    
    total_examples = sum(len(r["examples"]) for r in all_results)
    intent_correct = sum(
        1 for r in all_results
        for e in r["examples"]
        if e["detected_intent"] == r["intent"]
    )
    no_fallback = sum(
        1 for r in all_results
        for e in r["examples"]
        if not e["is_generic_fallback"]
    )
    
    print(f"Total Shortcuts: {len(all_results)}")
    print(f"Total Examples: {total_examples}")
    print(f"Intent Detection: {intent_correct}/{total_examples} ({intent_correct*100//total_examples}%)")
    print(f"No Generic Fallback: {no_fallback}/{total_examples} ({no_fallback*100//total_examples}%)")
    print(f"{'='*80}\n")
    
    # Verify all examples passed
    intent_failures = [
        (r["shortcut"], e["example"], e["detected_intent"], r["intent"])
        for r in all_results
        for e in r["examples"]
        if e["detected_intent"] != r["intent"]
    ]
    
    fallback_failures = [
        (r["shortcut"], e["example"])
        for r in all_results
        for e in r["examples"]
        if e["is_generic_fallback"]
    ]
    
    if intent_failures:
        error_msg = "\n".join(
            [
                f"❌ {shortcut} ({expected}): '{example}' → detected as '{detected}'"
                for shortcut, example, detected, expected in intent_failures
            ]
        )
        pytest.fail(f"Intent detection failures:\n{error_msg}")
    
    if fallback_failures:
        error_msg = "\n".join(
            [
                f"❌ {shortcut}: '{example}' → Generic fallback detected"
                for shortcut, example in fallback_failures
            ]
        )
        pytest.fail(f"Generic fallback detected for:\n{error_msg}")
