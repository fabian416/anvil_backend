@pytest.mark.asyncio
@pytest.mark.integration
async def test_user_shortcut_examples_detect_correct_intent(
    client: AsyncClient,
    shortcuts_data: list,
    conversation_id: str,
):
    """
    Test that all shortcut examples detect the correct intent for authenticated users.
    
    CTO Framework: Verification Phase
    - Dynamically fetches shortcuts from API endpoint
    - Tests each example from each shortcut
    - Verifies intent detection accuracy for authenticated users
    - Ensures no false positives/negatives
    - Outputs detailed results for each example
    """
    failures = []
    successes = []
    
    print(f"\n{'='*80}")
    print("CTO Framework: Intent Detection Verification")
    print(f"{'='*80}")
    print(f"Total shortcuts: {len(shortcuts_data)}")
    print(f"Conversation ID: {conversation_id}")
    print(f"{'='*80}\n")
    
    for shortcut in shortcuts_data:
        intent = shortcut["intent"]
        command = shortcut["command"]
        examples = shortcut.get("examples", [])
        
        print(f"\n📋 Testing Shortcut: {command} (intent: {intent})")
        print(f"   Examples to test: {len(examples)}")
        
        for idx, example in enumerate(examples, 1):
            print(f"   [{idx}/{len(examples)}] Testing: '{example}'")
            
            response = await client.post(
                f"/api/v1/user/chat/conversations/{conversation_id}/messages",
                json={"content": example, "language": "en"},
                headers={"Authorization": f"Bearer {ACCESS_TOKEN}"},
            )
            
            # Accept both 200 (existing conversation) and 201 (new conversation created)
            assert response.status_code in [200, 201], (
                f"Failed for {intent}: {example} - Status: {response.status_code}"
            )
            data = response.json()
            
            detected_intent = data.get("routing", {}).get("intent", "unknown")
            agent_content = data.get("agent_message", {}).get("content", "")
            
            if detected_intent == intent:
                print(f"      ✅ Intent correct: {detected_intent}")
                successes.append({
                    "shortcut": command,
                    "intent": intent,
                    "example": example,
                    "detected": detected_intent,
                })
            else:
                print(f"      ❌ Intent mismatch: expected '{intent}', got '{detected_intent}'")
                print(f"      Content preview: {agent_content[:80]}...")
                failures.append({
                    "shortcut": command,
                    "intent": intent,
                    "example": example,
                    "detected": detected_intent,
                    "content_preview": agent_content[:100],
                })
    
    print(f"\n{'='*80}")
    print(f"Results: {len(successes)} passed, {len(failures)} failed")
    print(f"{'='*80}\n")
    
    if failures:
        error_msg = "\n".join(
            [
                f"❌ {f['shortcut']} ({f['intent']}): '{f['example']}' → detected as '{f['detected']}'"
                for f in failures
            ]
        )
        pytest.fail(f"Intent detection failures:\n{error_msg}")


